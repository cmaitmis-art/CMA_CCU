/**
 * mc.js — Routes for Management Corporation (MC) Management
 * 
 * WHAT THIS FILE DOES:
 * Handles CRUD operations for Management Corporations:
 *   GET    /api/mc              → List MCs with search, filter, pagination
 *   GET    /api/mc/stats/summary → Count of MCs by status
 *   GET    /api/mc/:id          → Get single MC record
 *   POST   /api/mc              → Create new MC
 *   PATCH  /api/mc/:id          → Update an MC
 *   DELETE /api/mc/:id          → Delete an MC
 *   POST   /api/mc/bulk         → Bulk import/upsert from Excel data
 * 
 * NOTES:
 * - Uses Sequelize ORM (ManagementCorporation model)
 * - Uses Op.like (NOT Op.iLike) because SQLite doesn't support iLike.
 *   SQLite's LIKE is already case-insensitive for ASCII characters.
 */

