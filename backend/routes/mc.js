// ── POST /api/mc ─ Create one record ────────────────────────────────────────
router.post('/', async (req, res) => {
  try {
    let data = pickWritable(req.body);
    coerceInts(data, 'units', 'residential', 'non_residential', 'service_units',
      'residential_units', 'non_residential_units', 'year',
      'non_res_shops', 'non_res_office', 'non_res_hotel');
    normalizePayloadBooleans(data);
    if (Object.prototype.hasOwnProperty.call(data, 'council_members')) {
      data.council_members = normalizeCouncilMembers(data.council_members);
    }
    deriveFields(data, true);

    // Validate required fields
    if (!data.file_no) {
      return res.status(400).json({ error: 'file_no is required' });
    }
    if (!data.name && !data.management_corporation_name) {
      return res.status(400).json({ error: 'name / management_corporation_name is required' });
    }

    // Helpful fallback so UI values always exist
    if (data.management_corporation_name && !data.name) {
      data.name = data.management_corporation_name;
    }


    const created_by = req.body.created_by || req.body.user_name || 'System';
    const modified_by = req.body.modified_by || created_by;
    const user_name = req.body.user_name || created_by;
    const initialHistory = [{
      name: user_name,
      action: 'Added',
      time: new Date().toISOString(),
      note: 'Initial registration'
    }];

    const transaction = await db.sequelize.transaction();
    try {
      const record = await ManagementCorporation.create({
        ...data,
        created_by,
        modified_by,
        history: JSON.stringify(initialHistory),
      }, { transaction });

      const invoicePayload = buildInvoicePayload(record, data, req.body.invoice || {}, user_name);
      await RegistrationPayableInvoice.create(invoicePayload, { transaction });

      await transaction.commit();
      res.status(201).json(record.toJSON());
    } catch (invoiceErr) {
      await transaction.rollback();
      console.error('POST /mc invoice creation error:', invoiceErr);
      if (invoiceErr.name === 'SequelizeUniqueConstraintError') {
        return res.status(409).json({ error: 'Invoice could not be created: duplicate invoice number' });
      }
      return res.status(500).json({ error: invoiceErr.message });
    }
  } catch (err) {
    console.error('POST /mc error:', err);
    if (err.name === 'SequelizeUniqueConstraintError') {
      return res.status(409).json({ error: 'Duplicate file_no' });
    }
    res.status(500).json({ error: err.message });
  }
});

// ── PATCH /api/mc/:id ─ Update one record ───────────────────────────────────
router.patch('/:id', async (req, res) => {
  try {
    let data = pickWritable(req.body);
    if (typeof data.council_members === 'string') {
      try {
        data.council_members = JSON.parse(data.council_members);
      } catch (e) {
        data.council_members = [];
      }
    }
    coerceInts(data, 'units', 'residential', 'non_residential', 'service_units',
      'residential_units', 'non_residential_units', 'year',
      'non_res_shops', 'non_res_office', 'non_res_hotel', 'renewal_paid_year');
    normalizePayloadBooleans(data);
    if (Object.prototype.hasOwnProperty.call(data, 'council_members')) {
      data.council_members = normalizeCouncilMembers(data.council_members);
    }
    deriveFields(data, false);

    if (!Object.keys(data).length) {
      return res.status(400).json({ error: 'No fields to update' });
    }

    const record = await ManagementCorporation.findByPk(req.params.id);
    if (!record) return res.status(404).json({ error: 'Not found' });

    const modified_by = req.body.modified_by || req.body.user_name || 'System';
    const user_name = req.body.user_name || modified_by;
    let history = [];
    try {
      history = record.history ? JSON.parse(record.history) : [];
    } catch (e) {
      history = [];
    }

    const changedFields = [];
    const ignoreFields = ['updated_at', 'created_at', 'modified_by', 'created_by', 'history', 'user_name'];
    for (const key of Object.keys(data)) {
      if (ignoreFields.includes(key)) continue;
      const oldVal = record[key] === '' ? null : record[key];
      const newVal = data[key] === '' ? null : data[key];

      if ((oldVal == null) !== (newVal == null)) {
        const prettyKey = key.replace(/^cl_/, 'checklist: ').replace(/_/g, ' ');
        changedFields.push(prettyKey);
      } else if (oldVal != null && newVal != null) {
        if (String(oldVal) !== String(newVal)) {
          const prettyKey = key.replace(/^cl_/, 'checklist: ').replace(/_/g, ' ');
          changedFields.push(prettyKey);
        }
      }
    }

    let note = 'Modified record';
    if (data.status === 'Active' && record.status !== 'Active') {
      note = 'Approved & Activated record';
    } else if (data.status === 'Non Active' && record.status !== 'Non Active') {
      note = 'Rejected record';
    } else if (changedFields.length > 0) {
      note = `Updated ${changedFields.join(', ')}`;
    }

    history.push({
      name: user_name,
      action: 'Modified',
      time: new Date().toISOString(),
      note
    });

    await record.update({
      ...data,
      modified_by,
      history: JSON.stringify(history)
    });
    res.json(record.toJSON());
  } catch (err) {
    console.error('PATCH /mc/:id error:', err);
    res.status(500).json({ error: err.message });
  }
});

// ── POST /api/mc/bulk-delete ─ Delete multiple records by file_no ───────────
router.post('/bulk-delete', async (req, res) => {
  const { file_nos } = req.body;
  if (!Array.isArray(file_nos) || file_nos.length === 0) {
    return res.status(400).json({ error: 'file_nos must be a non-empty array' });
  }

  try {
    const transaction = await db.sequelize.transaction();
    try {
      const allMcs = await ManagementCorporation.findAll({ where: { file_no: file_nos }, attributes: ['id'], raw: true, transaction });
      const mcIds = allMcs.map(row => row.id);
      if (mcIds.length > 0) {
        if (db.models.RegistrationPayableInvoice) {
          await db.models.RegistrationPayableInvoice.destroy({ where: { mc_id: mcIds }, transaction });
        }
        if (db.models.AgmRecord) {
          await db.models.AgmRecord.destroy({ where: { mc_id: mcIds }, transaction });
        }
        if (db.models.Complaint) {
          await db.models.Complaint.update({ mc_id: null }, { where: { mc_id: mcIds }, transaction });
        }
      }
      const deleted = await ManagementCorporation.destroy({ where: { file_no: file_nos }, transaction });
      
      if (deleted > 0 && db.models.SystemLog) {
        const user = req.body.user_name || req.query.user_name || 'System';
        await db.models.SystemLog.create({
          user_name: user,
          action: 'Deleted MC records',
          details: `Bulk deleted ${deleted} records (File Nos: ${file_nos.join(', ')})`
        }, { transaction });
      }
      
      await transaction.commit();
      res.json({ message: 'Deleted records', deleted });
    } catch (err) {
      await transaction.rollback();
      throw err;
    }
  } catch (err) {
    console.error('POST /mc/bulk-delete error:', err.message);
    res.status(500).json({ error: 'Bulk delete failed: ' + err.message });
  }
});

// ── DELETE /api/mc ─ Delete ALL records ─────────────────────────────────────
router.delete('/', async (req, res) => {
  const transaction = await db.sequelize.transaction();
  try {
    const allMcs = await ManagementCorporation.findAll({ attributes: ['id'], raw: true, transaction });
    const mcIds = allMcs.map((row) => row.id);

    if (mcIds.length > 0) {
      if (db.models.RegistrationPayableInvoice) {
        await db.models.RegistrationPayableInvoice.destroy({ where: { mc_id: mcIds }, transaction });
      }
      if (db.models.AgmRecord) {
        await db.models.AgmRecord.destroy({ where: { mc_id: mcIds }, transaction });
      }
      if (db.models.Complaint) {
        await db.models.Complaint.update(
          { mc_id: null },
          { where: { mc_id: mcIds }, transaction }
        );
      }
    }

    const deleted = await ManagementCorporation.destroy({ where: {}, transaction });
    
    if (deleted > 0 && db.models.SystemLog) {
      const user = req.body.user_name || req.query.user_name || 'System';
      await db.models.SystemLog.create({
        user_name: user,
        action: 'Deleted ALL MC records',
        details: `Deleted all ${deleted} MC records`
      }, { transaction });
    }

    await transaction.commit();
    res.json({ message: 'All MC records deleted', deleted });
  } catch (err) {
    await transaction.rollback();
    console.error('DELETE /mc error:', err.message);
    res.status(500).json({ error: 'Failed to delete all records' });
  }
});

