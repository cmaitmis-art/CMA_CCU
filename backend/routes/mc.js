function buildInvoicePayload(mcRecord, payload, invoiceMeta = {}, userName = 'System') {
  const invoiceDate = invoiceMeta.invoice_date || payload.reg_date || new Date().toISOString().slice(0, 10);
  const registrationDate = invoiceMeta.registration_date || payload.reg_date || invoiceDate;
  const periodStart = invoiceMeta.period_start || payload.reg_date || invoiceDate;
  const startDate = new Date(periodStart);
  const startYear = Number.isNaN(startDate.getTime()) ? new Date().getFullYear() : startDate.getFullYear();
  const periodEnd = invoiceMeta.period_end || payload.next_renewal_date || `${startYear}-12-31`;
  const dueDate = invoiceMeta.due_date || periodEnd;
  const invoiceNumber = invoiceMeta.invoice_number || `INV-${mcRecord.file_no || mcRecord.id}-${Date.now()}`;

  return {
    mc_id: mcRecord.id,
    invoice_number: invoiceNumber,
    invoice_date: invoiceDate,
    registration_date: registrationDate,
    period_start: periodStart,
    period_end: periodEnd,
    due_date: dueDate,
    file_no: mcRecord.file_no,
    old_file_no: mcRecord.old_file_no,
    new_file_no: mcRecord.new_file_no,
    management_corporation_name: mcRecord.name || mcRecord.management_corporation_name,
    category: mcRecord.category,
    fee_rate_per_unit: mcRecord.fee_rate_per_unit,
    fee_amount: mcRecord.fee_amount,
    sscl_amount: mcRecord.sscl_amount,
    vat_amount: mcRecord.vat_amount,
    total_amount: mcRecord.total_amount,
    status: 'Payable',
    created_by: userName,
    modified_by: userName,
    history: JSON.stringify([
      {
        name: userName,
        action: 'Invoice Created',
        time: new Date().toISOString(),
      },
    ]),
  };
}

