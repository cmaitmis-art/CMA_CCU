  // Mark a renewal invoice as paid and auto-generate the Acknowledgement record.
  // NOTE: this PATCHes the MC record (`/api/mc/:id`) with the new renewal_paid* /
  // acknowledgement_* fields - the backend `mc` table needs matching columns for
  // this to persist (see BACKEND_FIELDS additions at the top of this file).
  async function markRenewalPaid(invoice) {
    if (!invoice) return;
    if (!invoice.mc_id) {
      showToast('Cannot find the MC record for this invoice', 'error');
      return;
    }
    const fmt = (n) => (n != null ? Number(n).toLocaleString('en-LK', { minimumFractionDigits: 2, maximumFractionDigits: 2 }) : '0.00');
    const confirmed = await confirm({
      title: 'Record Renewal Payment',
      message: `Confirm that Rs. ${fmt(invoice.total_amount)} has been received for this renewal? This will submit the payment for AGM approval.`,
      confirmLabel: 'Mark as Paid',
      cancelLabel: 'Cancel',
    });
    if (!confirmed) return;

    setMarkingRenewalPaid(true);
    try {
      const API_BASE = import.meta.env.VITE_API_URL ?? '/api';
      const today = new Date().toISOString().slice(0, 10);
      const year = invoice.period_end ? new Date(invoice.period_end).getFullYear() : new Date().getFullYear();
      const mcName = invoice.management_corporation_name || invoice.name || invoice.mc_name || 'MC';
      const fileNo = invoice.new_file_no || invoice.old_file_no || invoice.file_no || '-';
      const patchBody = {
        renewal_paid: true,
        renewal_payment_status: 'Pending Approval',
        renewal_paid_date: today,
        renewal_paid_amount: invoice.total_amount,
        renewal_paid_year: year,
        renewal_receipt_no: invoice.invoice_number,
      };
      const r = await fetch(`${API_BASE}/mc/${invoice.mc_id}`, {
        method: 'PATCH',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(patchBody),
      });
      const body = await r.json().catch(() => ({}));
      if (!r.ok) throw new Error(body.error || 'Failed to update payment status');

      // Send notification to AGM for approval
      fetch(`${API_BASE}/notifications`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          type: 'action_required',
          title: '- Renewal Payment Awaiting Approval',
          message: `Renewal payment of Rs. ${Number(invoice.total_amount || 0).toLocaleString('en-LK', { minimumFractionDigits: 2 })} for ${mcName} (File No: ${fileNo}) has been recorded by ${auditUserLabel}. Please review and approve.`,
          target_role: 'AGM',
          link: `mc:${invoice.mc_id}`,
        }),
      }).catch(() => { }); // Fire and forget

      // Send notification to all officers confirming the submission
      fetch(`${API_BASE}/notifications`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          type: 'success',
          title: 'Payment Recorded',
          message: `Renewal payment for ${mcName} (File No: ${fileNo}) has been successfully recorded and is now awaiting AGM approval. You will be notified once it is approved.`,
          target_role: 'MA',
          link: `mc:${invoice.mc_id}`,
        }),
      }).catch(() => { }); // Fire and forget

      setMcs((prev) => prev.map((item) => (item.id === invoice.mc_id ? { ...item, ...patchBody } : item)));
      setViewRecord((prev) => (prev && prev.id === invoice.mc_id ? { ...prev, ...patchBody } : prev));
      setInvoiceRecord((prev) => (prev ? { ...prev, ...patchBody } : prev));
      showToast('Payment recorded and sent for AGM approval -');
    } catch (err) {
      showToast(err.message || 'Failed to update payment status', 'error');
    } finally {
      setMarkingRenewalPaid(false);
    }
  }

