        const approvedBy = currentUser?.name || currentUser?.username || 'AGM';
        const created = await createNotification({
          type: 'success',
          title: 'MC Approved',
          message: `File No: ${fileNo} | Name: "${mcName}" | Approved: ${today} by ${approvedBy}.`,
          target_role: null, // broadcast to all users
          link: `mc:${checklistRecord.id}`,
        });
