export function createAutoGeneratedFileNo() {
  const stamp = Date.now().toString(36).toUpperCase();
  return `MC-${stamp}`;
}

export function hasAcknowledgementPayload(record = {}) {
  return Boolean(
    record?.renewal_paid ||
    record?.acknowledgement_no ||
    record?.acknowledgement_date ||
    record?.renewal_receipt_no ||
    record?.renewal_paid_year != null ||
    record?.renewal_paid_amount != null
  );
}

export function canApproveWithAgmChecklist(values = {}, record = {}) {
  const hasRequiredChecklist = ['cl_agm_minutes', 'cl_attendance'].every((key) => Boolean(values?.[key]));
  return hasRequiredChecklist || hasAcknowledgementPayload(record);
}

export function serializeCouncilMembers(rows = []) {
  const filtered = (Array.isArray(rows) ? rows : [])
    .filter((row) => row && (row.name || row.unit_no || row.contact_no))
    .map((row) => ({
      name: row.name || '',
      unit_no: row.unit_no || '',
      contact_no: row.contact_no || '',
    }));

  return JSON.stringify(filtered);
}

export function buildMcTablePrintHtml(rows = [], { title = 'MC Management Records' } = {}) {
  const safeRows = Array.isArray(rows) ? rows : [];
  const headers = ['File No', 'Name', 'Category', 'Status', 'Town', 'Reg Date'];

  const escapeHtml = (value) => String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

  const rowsHtml = safeRows.map((row) => {
    const fileNo = escapeHtml(row?.new_file_no || row?.file_no || row?.old_file_no || '');
    const name = escapeHtml(row?.name || row?.management_corporation_name || '');
    const category = escapeHtml(row?.category || '');
    const status = escapeHtml(row?.status || '');
    const town = escapeHtml(row?.town || '');
    const regDate = escapeHtml(row?.reg_date || '');

    return `
      <tr>
        <td>${fileNo}</td>
        <td>${name}</td>
        <td>${category}</td>
        <td>${status}</td>
        <td>${town}</td>
        <td>${regDate}</td>
      </tr>`;
  }).join('');

  return `<!doctype html>
  <html>
    <head>
      <meta charset="utf-8" />
      <title>${escapeHtml(title)}</title>
      <style>
        body { font-family: Arial, sans-serif; color: #111; padding: 24px; }
        h1 { font-size: 20px; margin-bottom: 8px; }
        .meta { color: #555; font-size: 12px; margin-bottom: 14px; }
        table { width: 100%; border-collapse: collapse; font-size: 11px; }
        th, td { border: 1px solid #bbb; padding: 6px 8px; text-align: left; vertical-align: top; }
        th { background: #f2f2f2; }
      </style>
    </head>
    <body>
      <h1>${escapeHtml(title)}</h1>
      <div class="meta">Generated from MC Management</div>
      <table>
        <thead>
          <tr>${headers.map((header) => `<th>${escapeHtml(header)}</th>`).join('')}</tr>
        </thead>
        <tbody>${rowsHtml || '<tr><td colspan="6">No records</td></tr>'}</tbody>
      </table>
    </body>
  </html>`;
}

export function buildMcTablePdfData(rows = []) {
  const safeRows = Array.isArray(rows) ? rows : [];
  return safeRows.map((row) => ({
    fileNo: row?.new_file_no || row?.file_no || row?.old_file_no || '',
    name: row?.name || row?.management_corporation_name || '',
    category: row?.category || '',
    status: row?.status || '',
    town: row?.town || '',
    regDate: row?.reg_date || '',
  }));
}
