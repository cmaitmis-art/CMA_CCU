import { describe, expect, it } from 'vitest';
import { createAutoGeneratedFileNo, serializeCouncilMembers, buildMcTablePrintHtml, buildMcTablePdfData, canApproveWithAgmChecklist, hasAcknowledgementPayload } from './mcManagementUtils.js';

describe('mc management helpers', () => {
  it('creates a fallback file number when none is supplied', () => {
    const fileNo = createAutoGeneratedFileNo();

    expect(fileNo).toMatch(/^MC-/);
    expect(fileNo.length).toBeGreaterThan(6);
  });

  it('serializes council members while removing empty rows', () => {
    const serialized = serializeCouncilMembers([
      { name: 'A', unit_no: '1', contact_no: '111' },
      { name: '', unit_no: '', contact_no: '' },
      { name: 'B', unit_no: '2', contact_no: '222' },
    ]);

    expect(serialized).toBe('[{"name":"A","unit_no":"1","contact_no":"111"},{"name":"B","unit_no":"2","contact_no":"222"}]');
  });

  it('builds a printable HTML table for MC records', () => {
    const html = buildMcTablePrintHtml([
      { file_no: 'MC-001', name: 'Sample MC', category: 'Luxury', status: 'Active', town: 'Colombo', reg_date: '2026-01-01' },
    ], { title: 'MC Management Records' });

    expect(html).toContain('<table');
    expect(html).toContain('MC Management Records');
    expect(html).toContain('File No');
    expect(html).toContain('MC-001');
  });

  it('maps MC rows into PDF-ready data', () => {
    const data = buildMcTablePdfData([
      { file_no: 'MC-001', name: 'Sample MC', category: 'Luxury', status: 'Active', town: 'Colombo', reg_date: '2026-01-01' },
    ]);

    expect(data[0]).toMatchObject({ fileNo: 'MC-001', name: 'Sample MC' });
  });

  it('allows approval when payment acknowledgement data is already present', () => {
    const values = { cl_agm_minutes: false, cl_attendance: false };
    const record = { renewal_paid: true, acknowledgement_no: 'ACK/123', acknowledgement_date: '2026-07-16' };

    expect(canApproveWithAgmChecklist(values, record)).toBe(true);
  });

  it('detects acknowledgement payload values from an MC record', () => {
    expect(hasAcknowledgementPayload({ renewal_paid: true })).toBe(true);
    expect(hasAcknowledgementPayload({ acknowledgement_no: 'ACK/123' })).toBe(true);
    expect(hasAcknowledgementPayload({ renewal_paid_amount: 2500 })).toBe(true);
    expect(hasAcknowledgementPayload({ status: 'Pending' })).toBe(false);
  });
});
